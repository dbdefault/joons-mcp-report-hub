const SCRIPT_TEXT = `(function () {
  'use strict';
  function applyFilter(state) {
    var nodes = document.querySelectorAll('[data-state]');
    for (var i = 0; i < nodes.length; i += 1) {
      var match = state === 'all' || nodes[i].getAttribute('data-state') === state;
      nodes[i].hidden = !match;
    }
  }
  function setDetails(open) {
    var nodes = document.querySelectorAll('main details');
    for (var i = 0; i < nodes.length; i += 1) {
      nodes[i].open = open;
    }
  }
  var filters = document.querySelectorAll('[data-filter]');
  for (var j = 0; j < filters.length; j += 1) {
    filters[j].addEventListener('click', function (event) {
      applyFilter(event.currentTarget.getAttribute('data-filter'));
    });
  }
  var expand = document.getElementById('expand-all');
  if (expand) { expand.addEventListener('click', function () { setDetails(true); }); }
  var collapse = document.getElementById('collapse-all');
  if (collapse) { collapse.addEventListener('click', function () { setDetails(false); }); }
})();`;

function sha256Base64(text) {
  return createHash('sha256').update(text, 'utf8').digest('base64');
}

function esc(value) {
  return escapeHtml(stripControls(String(value), { keepNewlines: false }))
    .replace(/javascript:/gi, (s) => s.slice(0, -1) + '&#58;')
    .replace(/[=()]/g, (ch) => `&#${ch.charCodeAt(0)};`);
}

function asObject(value) {
  return value && typeof value === 'object' && !Array.isArray(value) ? value : {};
}

function asArray(value) {
  return Array.isArray(value) ? value : [];
}

function levelState(level) {
  return LEVEL_STATES.has(level) ? level : 'info';
}

function kindLabel(kind) {
  return Object.prototype.hasOwnProperty.call(KIND_LABELS, kind) ? KIND_LABELS[kind] : esc(kind);
}

function reportLevel(report) {
  const status = asObject(report && report.status);
  const rank = LEVEL_RANK[status.level];
  return rank === undefined ? 0 : rank;
}

function worstReport(reports) {
  let worst = null;
  for (const report of reports) {
    if (!worst || reportLevel(report) > reportLevel(worst)) worst = report;
  }
  return worst;
}

function idNumber(report) {
  const m = /^r(\d+)$/.exec(String(report && report.id));
  return m ? Number(m[1]) : 0;
}

function countValueText(value) {
  if (Number.isFinite(value)) return String(value);
  if (value === null || value === undefined) return 'not available';
  if (typeof value === 'object') {
    return Object.entries(value)
      .map(([k, v]) => `${esc(k)}: ${Number.isFinite(v) ? String(v) : 'not available'}`)
      .join(', ');
  }
  return esc(value);
}

function renderReportDetailsBlock(report) {
  const lines = [];
  const source = asObject(report.source);
  if (typeof source.label === 'string') {
    const sha = typeof source.sha256 === 'string' ? ` (${esc(source.sha256)})` : '';
    lines.push(`<p class="muted">Source: ${esc(source.label)}${sha}</p>`);
  }
  if (typeof source.fileName === 'string' && source.fileName) {
    lines.push(`<p class="muted">File: ${esc(source.fileName)}</p>`);
  }
  if (typeof report.productVersion === 'string' && report.productVersion) {
    lines.push(`<p class="muted">Product version: ${esc(report.productVersion)}</p>`);
  }
  const counts = asObject(report.counts);
  const countKeys = Object.keys(counts);
  if (countKeys.length > 0) {
    lines.push('<h4>Counts</h4>');
    lines.push('<ul>');
    for (const key of countKeys) {
      lines.push(`<li>${esc(key)}: ${countValueText(counts[key])}</li>`);
    }
    lines.push('</ul>');
  }
  const findings = asArray(report.findings);
  lines.push('<h4>Findings</h4>');
  if (findings.length === 0) {
    lines.push('<p>No findings.</p>');
  } else {
    lines.push('<ul>');
    for (const finding of findings) {
      const severity = esc(finding.severity);
      const code = esc(finding.code);
      const count = Number.isFinite(finding.count) ? finding.count : 0;
      lines.push(`<li>[${severity}] ${code} x${count}</li>`);
      const details = asArray(finding.details);
      if (details.length > 0) {
        lines.push('<ul>');
        for (const detail of details) {
          const subject = typeof detail.subject === 'string' ? esc(detail.subject) : '';
          const message = typeof detail.message === 'string' ? esc(detail.message) : '';
          lines.push(`<li>${subject}: ${message}</li>`);
        }
        lines.push('</ul>');
      }
    }
    lines.push('</ul>');
  }
  const notAvailable = asArray(report.notAvailable);
  if (notAvailable.length > 0) {
    lines.push(`<p class="muted">Not available: ${notAvailable.map((f) => esc(f)).join(', ')}</p>`);
  }
  return lines.join('\n');
}

export function renderDashboardHtml(summary) {
  const s = asObject(summary);
  const overall = asObject(s.overall);
  const totals = asObject(s.totals);
  const mode = asObject(s.mode);
  const products = asObject(s.products);
  const reports = asArray(s.reports).filter((r) => r && typeof r === 'object');
  const problems = asArray(s.problems);
  const rate = asObject(s.testSuccessRate);

  const overallStatus = typeof overall.status === 'string' ? overall.status : 'NO_DATA';
  const chip = OVERALL_CHIP[overallStatus] || 'info';

  const styleHash = sha256Base64(STYLE_TEXT);
  const scriptHash = sha256Base64(SCRIPT_TEXT);

  const files = Number.isFinite(totals.files) ? totals.files : 0;
  const reportCount = Number.isFinite(totals.reports) ? totals.reports : reports.length;
  const duplicates = Number.isFinite(totals.duplicates) ? totals.duplicates : 0;
  const ignored = Number.isFinite(totals.ignored) ? totals.ignored : 0;
  const rejected = Number.isFinite(totals.rejected) ? totals.rejected : 0;

  const lines = [];
  lines.push('<!doctype html>');
  lines.push('<html lang="en">');
  lines.push('<head>');
  lines.push('<meta charset="utf-8">');
  lines.push('<meta name="viewport" content="width=device-width, initial-scale=1">');
  lines.push(
    `<meta http-equiv="Content-Security-Policy" content="default-src 'none'; ` +
      `style-src 'sha256-${styleHash}'; script-src 'sha256-${scriptHash}'; ` +
      `img-src data:; base-uri 'none'; form-action 'none'">`
  );
  lines.push('<title>MCP Report Hub</title>');
  lines.push(`<style>${STYLE_TEXT}</style>`);
  lines.push('</head>');
  lines.push('<body>');
  lines.push('<div class="container">');

  // Header
  lines.push('<header class="site-header">');
  lines.push('<h1>MCP Report Hub</h1>');
  lines.push(`<p><span class="chip chip-${chip}">Overall: ${esc(OVERALL_TEXT[overallStatus] || overallStatus)}</span></p>`);
  if (typeof s.generatedAt === 'string' && s.generatedAt) {
    lines.push(`<p>Generated: ${esc(s.generatedAt)}</p>`);
  } else {
    lines.push('<p>Generated: not recorded</p>');
  }
  const modeNote =
    `Mode: details ${mode.details ? 'on' : 'off'}, ` +
    `file names ${mode.showFileNames ? 'shown' : 'hidden'}, ` +
    `duplicates: ${esc(typeof mode.duplicates === 'string' ? mode.duplicates : 'keep-first')}`;
  lines.push(`<p class="muted">${modeNote}</p>`);
  if (mode.details === true) {
    lines.push(`<p class="banner" role="alert">${DETAILS_BANNER}</p>`);
  }
  lines.push(
    '<p class="toolbar" aria-label="Report filters">' +
      '<button type="button" data-filter="all">All</button>' +
      '<button type="button" data-filter="failure">Failing</button>' +
      '<button type="button" data-filter="warning">Warnings</button>' +
      '</p>'
  );
  lines.push('</header>');

  lines.push('<main>');

  // Overall card
  lines.push('<section id="overall" class="card" aria-labelledby="overall-heading">');
  lines.push('<h2 id="overall-heading">Overall result</h2>');
  lines.push(
    `<p>Status: <span class="chip chip-${chip}">${esc(OVERALL_TEXT[overallStatus] || overallStatus)}</span></p>`
  );
  const reasons = asArray(overall.reasons);
  lines.push('<h4>Reasons</h4>');
  if (reasons.length === 0) {
    lines.push('<p>No reasons recorded.</p>');
  } else {
    lines.push('<ul>');
    for (const reason of reasons) lines.push(`<li>${esc(reason)}</li>`);
    lines.push('</ul>');
  }
  const plural = (n, word) => `${n} ${word}${n === 1 ? '' : 's'}`;
  lines.push(
    `<p class="muted">Inputs: ${plural(files, 'file')}, ${plural(reportCount, 'report')}, ` +
      `${plural(duplicates, 'duplicate')}, ${ignored} ignored, ${rejected} rejected</p>`
  );
  lines.push('</section>');

  // Empty input state
  if (reports.length === 0) {
    lines.push('<section id="empty-state" class="card" aria-labelledby="empty-heading">');
    lines.push('<h2 id="empty-heading">No reports</h2>');
    lines.push(`<p>${EMPTY_STATE_MESSAGE}</p>`);
    lines.push('</section>');
  }

  // Product cards (all five)
  lines.push('<section id="products" aria-labelledby="products-heading">');
  lines.push('<h2 id="products-heading">Products</h2>');
  lines.push('<div class="grid">');
  for (const product of PRODUCT_ORDER) {
    const productReports = reports.filter((r) => r.product === product);
    const entry = asObject(products[product]);
    lines.push('<div class="card">');
    lines.push(`<h3>${PRODUCT_TITLES[product]}</h3>`);
    if (productReports.length === 0) {
      lines.push('<p>No reports</p>');
    } else {
      const worst = worstReport(productReports);
      const status = asObject(worst.status);
      const level = typeof entry.level === 'string' ? entry.level : 'none';
      const reportTotal = Number.isFinite(entry.reports) ? entry.reports : productReports.length;
      lines.push(`<p>${reportTotal} report${reportTotal === 1 ? '' : 's'}</p>`);
      lines.push(
        `<p>Level: <span class="chip chip-${levelState(level)}">${esc(level)}</span></p>`
      );
      const value = typeof status.value === 'string' ? esc(status.value) : 'unknown';
      lines.push(`<p>Status: ${value} (${kindLabel(status.kind)})</p>`);
    }
    lines.push('</div>');
  }
  lines.push('</div>');
  lines.push('</section>');

  // Failing items: failures first, then warnings (fail/warn findings and
  // failure/warning-level reports, severity rank first)
  const items = [];
  reports.forEach((report, index) => {
    const productIndex = PRODUCT_ORDER.indexOf(report.product);
    const status = asObject(report.status);
    const level = reportLevel(report);
    if (level === LEVEL_RANK.failure || level === LEVEL_RANK.warning) {
      const rank = level === LEVEL_RANK.failure ? 0 : 1;
      items.push({
        rank,
        productIndex: productIndex === -1 ? PRODUCT_ORDER.length : productIndex,
        idNum: idNumber(report),
        seq: index,
        html:
          `<li class="item-${rank === 0 ? 'failure' : 'warning'}">[${rank === 0 ? 'failure' : 'warning'}] ` +
          `${esc(PRODUCT_TITLES[report.product] || report.product)} ${esc(report.id)} - ` +
          `${esc(status.value)} (${kindLabel(status.kind)})</li>`,
      });
    }
    asArray(report.findings).forEach((finding, findingIndex) => {
      const sev = finding.severity === 'fail' ? 0 : finding.severity === 'warn' ? 1 : -1;
      if (sev === -1) return;
      items.push({
        rank: sev,
        productIndex: productIndex === -1 ? PRODUCT_ORDER.length : productIndex,
        idNum: idNumber(report),
        seq: index + findingIndex / 1000,
        html:
          `<li class="item-${sev === 0 ? 'failure' : 'warning'}">[${finding.severity === 'fail' ? 'fail' : 'warn'}] ` +
          `${esc(PRODUCT_TITLES[report.product] || report.product)} ${esc(report.id)} ` +
          `${esc(finding.code)} x${Number.isFinite(finding.count) ? finding.count : 0}</li>`,
      });
    });
  });
  items.sort((a, b) =>
    a.rank !== b.rank
      ? a.rank - b.rank
      : a.productIndex !== b.productIndex
        ? a.productIndex - b.productIndex
        : a.idNum !== b.idNum
          ? a.idNum - b.idNum
          : a.seq - b.seq
  );
  lines.push('<section id="failing-items" aria-labelledby="failing-heading">');
  lines.push('<h2 id="failing-heading">Failing items (failures first)</h2>');
  if (items.length === 0) {
    lines.push('<p>No failing or warning items.</p>');
  } else {
    lines.push('<ul>');
    for (const item of items) lines.push(item.html);
    lines.push('</ul>');
  }
  lines.push('</section>');

  // Test success rate
  lines.push('<section id="test-success-rate" class="card" aria-labelledby="rate-heading">');
  lines.push('<h2 id="rate-heading">Test success rate</h2>');
  if (Number.isInteger(rate.percent)) {
    lines.push(`<p>${rate.percent}% (${rate.passed} passed, ${rate.failed} failed)</p>`);
  } else {
    lines.push('<p>No test results recorded.</p>');
  }
  lines.push('</section>');

  // Per-report table
  lines.push('<section id="reports" aria-labelledby="reports-heading">');
  lines.push('<h2 id="reports-heading">Reports</h2>');
  lines.push('<div class="table-wrap">');
  lines.push('<table>');
  lines.push(
    '<thead><tr><th scope="col">ID</th><th scope="col">Product</th><th scope="col">Status</th>' +
      '<th scope="col">Timestamp</th><th scope="col">Duration</th></tr></thead>'
  );
  lines.push('<tbody>');
  for (const report of reports) {
    const status = asObject(report.status);
    const state = levelState(status.level);
    const value = typeof status.value === 'string' ? esc(status.value) : 'unknown';
    const timestamp =
      typeof report.timestamp === 'string' && report.timestamp
        ? esc(report.timestamp)
        : 'not available';
    const duration = Number.isFinite(report.durationMs)
      ? `${report.durationMs} ms`
      : 'not available';
    lines.push(`<tr data-state="${state}">`);
    lines.push(`<td>${esc(report.id)}</td>`);
    lines.push(`<td>${esc(PRODUCT_TITLES[report.product] || report.product)}</td>`);
    lines.push(`<td>${value} (${kindLabel(status.kind)})</td>`);
    lines.push(`<td>${timestamp}</td>`);
    lines.push(`<td>${duration}</td>`);
    lines.push('</tr>');
  }
  lines.push('</tbody>');
  lines.push('</table>');
  lines.push('</div>');
  lines.push('</section>');

  // Per-report details
  lines.push('<section id="report-details" aria-labelledby="details-heading">');
  lines.push('<h2 id="details-heading">Report details</h2>');
  lines.push(
    '<p class="toolbar">' +
      '<button type="button" id="expand-all">Expand all</button>' +
      '<button type="button" id="collapse-all">Collapse all</button>' +
      '</p>'
  );
  for (const report of reports) {
    const status = asObject(report.status);
    const state = levelState(status.level);
    const title = esc(PRODUCT_TITLES[report.product] || report.product);
    const reportType = typeof report.reportType === 'string' ? esc(report.reportType) : '';
    lines.push(`<details data-state="${state}">`);
    lines.push(`<summary>${esc(report.id)} - ${title} - ${reportType}</summary>`);
    lines.push(renderReportDetailsBlock(report));
    lines.push('</details>');
  }
  lines.push('</section>');

  // Problems
  lines.push('<section id="problems" aria-labelledby="problems-heading">');
  lines.push('<h2 id="problems-heading">Unsupported or rejected inputs</h2>');
  if (problems.length === 0) {
    lines.push('<p>No unsupported or rejected inputs.</p>');
  } else {
    lines.push('<ul>');
    for (const problem of problems) {
      const p = asObject(problem);
      const source = asObject(p.source);
      const label = typeof source.label === 'string' ? esc(source.label) : 'report-?';
      const detail = typeof p.detail === 'string' ? esc(p.detail) : '';
      lines.push(`<li>${esc(p.kind)} - ${label} - ${detail}</li>`);
    }
    lines.push('</ul>');
  }
  lines.push('</section>');

  // Missing information
  lines.push('<section id="missing-information" aria-labelledby="missing-heading">');
  lines.push('<h2 id="missing-heading">Missing information</h2>');
  const missing = reports.filter((r) => asArray(r.notAvailable).length > 0);
  if (missing.length === 0) {
    lines.push('<p>No missing information.</p>');
  } else {
    lines.push('<ul>');
    for (const report of missing) {
      const fields = asArray(report.notAvailable)
        .map((f) => esc(f))
        .join(', ');
      lines.push(`<li>${esc(report.id)}: ${fields}</li>`);
    }
    lines.push('</ul>');
  }
  lines.push('</section>');

  lines.push('</main>');

  // Footer
  lines.push('<footer class="site-footer">');
  lines.push(`<p>${FOOTER_AGGREGATION}</p>`);
  lines.push(`<p class="muted">${FOOTER_TOOL}</p>`);
  lines.push('</footer>');

  lines.push('</div>');
  lines.push(`<script>${SCRIPT_TEXT}</script>`);
  lines.push('</body>');
  lines.push('</html>');

  return { html: lines.join('\n') + '\n' };
}
