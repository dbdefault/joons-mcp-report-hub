// Static, self-contained dashboard (index.html).
// - One inline <style> and one inline <script>; the CSP meta carries the real
//   base64 SHA-256 of each block, computed at render time with node:crypto.
// - No external resource of any kind; no href/src/url()/link/form/iframe.
// - Every dynamic value goes through escapeHtml into text nodes only; class
//   names and ids come from fixed enums. Dynamic text is also control-stripped
//   (aggregation already redacts; this is defense in depth).
// - The inline script only adds filter (all/failing/warnings) and
//   expand/collapse; the page is fully readable with scripting disabled.

import { createHash } from 'node:crypto';
import { escapeHtml } from '../security/escape.js';
import { stripControls } from '../util/object.js';

const KIND_LABELS = Object.freeze({
  health: 'Server health',
  change_risk: 'Change risk',
  policy: 'Policy compliance',
  tests: 'Test results',
  recording: 'Mock session recording (not a test result)',
  validation: 'Input validation',
});

const PRODUCT_ORDER = ['probe', 'diff', 'policy-gate', 'mock-server', 'contract-runner'];

const PRODUCT_TITLES = Object.freeze({
  probe: 'Probe',
  diff: 'Diff',
  'policy-gate': 'Policy Gate',
  'mock-server': 'Mock Server',
  'contract-runner': 'Contract Runner',
});

const LEVEL_RANK = Object.freeze({ none: 0, info: 1, ok: 2, warning: 3, failure: 4 });

const LEVEL_STATES = new Set(['ok', 'warning', 'failure', 'info']);

const OVERALL_CHIP = Object.freeze({ PASS: 'ok', WARN: 'warning', FAIL: 'failure', NO_DATA: 'info' });

const OVERALL_TEXT = Object.freeze({ PASS: 'PASS', WARN: 'WARN', FAIL: 'FAIL', NO_DATA: 'NO DATA' });

